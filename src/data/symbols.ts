export const SYMBOLS: SymbolInfo[] = [
  ...INDICES,
  ...ITALIAN_STOCKS,
  ...US_STOCKS,
  ...CRYPTO_PAIRS,
  ...FOREX_PAIRS,
  ...FUTURES,
  ...BONDS_AND_ETFS,
];

const symbolByTickerMap = new Map<string, SymbolInfo>(
  SYMBOLS.map((s) => [s.ticker.toUpperCase(), s]),
);

const symbolByIdMap = new Map<string, SymbolInfo>(
  SYMBOLS.map((s) => [s.id.toUpperCase(), s]),
);

export function getSymbolByTicker(ticker: string): SymbolInfo | undefined {
  const key = ticker.trim().toUpperCase();
  if (symbolByTickerMap.has(key)) return symbolByTickerMap.get(key);
  if (symbolByIdMap.has(key)) return symbolByIdMap.get(key);
  const parts = key.split(':');
  if (parts.length === 2) {
    return symbolByTickerMap.get(parts[1]);
  }
  return undefined;
}

export function getSymbolById(id: string): SymbolInfo | undefined {
  return symbolByIdMap.get(id.trim().toUpperCase()) ?? getSymbolByTicker(id);
}

export function getSymbolsByAssetClass(assetClass: AssetClass): SymbolInfo[] {
  return SYMBOLS.filter((s) => s.assetClass === assetClass);
}

export function searchSymbols(query: string, assetClass?: AssetClass): SymbolInfo[] {
  const q = query.trim().toLowerCase();
  const base = assetClass ? getSymbolsByAssetClass(assetClass) : SYMBOLS;
  if (!q) return base;
  return base.filter(
    (s) =>
      s.ticker.toLowerCase().includes(q) ||
      s.id.toLowerCase().includes(q) ||
      s.name.toLowerCase().includes(q) ||
      s.exchange.toLowerCase().includes(q) ||
      s.sector.toLowerCase().includes(q) ||
      s.description.toLowerCase().includes(q),
  );
}

