/**
 * Formats prices in Italian locale with smart sub-cent precision support
 * (e.g. PEPE/SHIB/BONK/FLOKI render as `0,00001234` instead of `0,00`).
 */
export function formatPrice(price: number, precision?: number): string {
  if (!Number.isFinite(price)) return '—';
  const abs = Math.abs(price);
  let resolvedPrecision = precision;
  if (resolvedPrecision === undefined) {
    resolvedPrecision = abs > 0 && abs < 0.0001 ? 8 : abs > 0 && abs < 0.01 ? 6 : abs > 0 && abs < 1 ? 4 : 2;
  } else if (abs > 0 && abs < 0.001 && resolvedPrecision < 6) {
    resolvedPrecision = abs < 0.0001 ? 8 : 6;
  }
  const clamped = Math.max(0, Math.min(8, Math.round(resolvedPrecision)));
  return price.toLocaleString('it-IT', {
    minimumFractionDigits: clamped,
    maximumFractionDigits: clamped,
  });
}

export function formatPercent(value: number, showSign = true): string {
  if (!Number.isFinite(value)) return '—';
  const sign = showSign && value > 0 ? '+' : '';
  return `${sign}${value.toLocaleString('it-IT', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}%`;
}

export function formatVolume(volume: number): string {
  if (!Number.isFinite(volume)) return '—';
  const abs = Math.abs(volume);
  if (abs >= 1_000_000_000) return `${(volume / 1_000_000_000).toFixed(2)}B`;
  if (abs >= 1_000_000) return `${(volume / 1_000_000).toFixed(2)}M`;
  if (abs >= 1_000) return `${(volume / 1_000).toFixed(2)}K`;
  return volume.toFixed(abs < 10 ? 2 : 0);
}

export function formatMarketCap(billions?: number | null): string {
  if (billions == null || !Number.isFinite(billions) || billions <= 0) return '—';
  if (billions >= 1000) return `${(billions / 1000).toFixed(2)}T`;
  return `${billions.toFixed(1)}B`;
}
