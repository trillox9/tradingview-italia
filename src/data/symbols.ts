function makeUsStock(s: UsStockSeed): SymbolInfo {
  const [
    ticker,
    exchange,
    name,
    shortName,
    sector,
    basePrice,
    prevClose,
    marketCap,
    peRatio,
    dividendYield,
    logoColor,
  ] = s;
  const vol = sector === 'Tecnologia' || sector === 'Automotive' ? 0.022 : 0.014;
  return {
    id: `${exchange}:${ticker}`,
    ticker,
    exchange,
    name,
    shortName,
    description: `${name} — Azione USA (${exchange}, ${sector})`,
    assetClass: 'stock',
    currency: 'USD',
    country: 'US',
    sector,
    basePrice,
    prevClose,
    precision: 2,
    tickSize: 0.01,
    volatility: vol,
    drift: 0.11,
    avgVolume: Math.round(Math.max(1_500_000, (marketCap * 45_000) / Math.max(10, basePrice) * 100)),
    marketCap,
    peRatio,
    dividendYield,
    beta: sector === 'Tecnologia' ? 1.25 : 0.96,
    eps: peRatio && peRatio > 0 ? Math.round((basePrice / peRatio) * 100) / 100 : undefined,
    high52w: Math.round(basePrice * 1.24 * 100) / 100,
    low52w: Math.round(basePrice * 0.72 * 100) / 100,
    yahooSymbol: ticker,
    logoColor: logoColor ?? pickColor(ticker),
    logoText: ticker.replace('-', '').slice(0, 2),
    marketStatus: 'open',
  };
}

