function pickColor(seed: string): string {
  let h = 0;
  for (let i = 0; i < seed.length; i++) {
    h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  }
  return PALETTE[h % PALETTE.length];
}

function smartPrecision(price: number): number {
  if (price < 0.0001) return 8;
  if (price < 0.01) return 6;
  if (price < 1) return 4;
  if (price < 10) return 3;
  return 2;
}

function tickForPrecision(precision: number): number {
  return Number((1 / Math.pow(10, precision)).toFixed(precision));
}

function monogram(ticker: string): string {
  const clean = ticker.replace(/USDT$/i, '').replace(/[^A-Z0-9]/gi, '');
  if (clean.length <= 3) return clean.toUpperCase();
  return clean.slice(0, 3).toUpperCase();
}

