const HEATMAP_SECTOR_ORDER = [
  'Tecnologia',
  'Finanza',
  'Energia',
  'Automotive',
  'Lusso',
  'Sanità',
] as const;

/**
 * Builds structured heatmap sectors from the stock catalog,
 * optionally overlaid with live QuoteTick prices/changes.
 */
export function buildHeatmapSectors(
  liveQuotes?: Map<string, QuoteTick>,
): HeatmapSector[] {
  const stocks = SYMBOLS.filter((s) => s.assetClass === 'stock');

  return HEATMAP_SECTOR_ORDER.map((sectorName) => {
    const sectorStocks: HeatmapStock[] = stocks
      .filter((s) => s.sector === sectorName)
      .map((s) => {
        const live = liveQuotes?.get(s.ticker);
        const price = live?.price ?? s.basePrice;
        const changePercent =
          live?.changePercent ??
          Math.round(((s.basePrice - s.prevClose) / s.prevClose) * 10000) / 100;
        return {
          ticker: s.ticker,
          name: s.shortName,
          exchange: s.exchange,
          sector: sectorName,
          marketCap: s.marketCap ?? 10,
          price,
          changePercent,
          volume: live?.volume ?? s.avgVolume,
        };
      })
      .sort((a, b) => b.marketCap - a.marketCap);

    const totalMarketCap = sectorStocks.reduce((acc, s) => acc + s.marketCap, 0);
    const weightedChange =
      totalMarketCap > 0
        ? sectorStocks.reduce((acc, s) => acc + s.changePercent * s.marketCap, 0) /
          totalMarketCap
        : 0;

    return {
      id: `sector-${sectorName.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
      name: sectorName,
      avgChangePercent: Math.round(weightedChange * 100) / 100,
      totalMarketCap: Math.round(totalMarketCap * 10) / 10,
      stocks: sectorStocks,
    };
  });
}

export const HEATMAP_SECTORS: HeatmapSector[] = buildHeatmapSectors();
